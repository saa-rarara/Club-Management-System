INSERT INTO Approval_Decisions
(application_id, faculty_id, admin_id, decision, comments, decision_date)
SELECT
    a.application_id,
    CASE
        WHEN MOD(a.application_id, 2) = 0 THEN f.faculty_id
        ELSE NULL
    END,
    CASE
        WHEN MOD(a.application_id, 2) = 1 THEN ad.admin_id
        ELSE NULL
    END,
    a.application_status,
    CASE a.application_status
        WHEN 'Approved' THEN 'Application approved.'
        WHEN 'Rejected' THEN 'Application rejected.'
        ELSE 'Awaiting final review.'
    END,
    CURDATE()
FROM Applications a
CROSS JOIN (
    SELECT faculty_id FROM Faculty_Advisors ORDER BY RAND() LIMIT 1
) f
CROSS JOIN (
    SELECT admin_id FROM Admin_Representatives ORDER BY RAND() LIMIT 1
) ad
WHERE NOT EXISTS (
    SELECT 1
    FROM Approval_Decisions d
    WHERE d.application_id = a.application_id
)
ORDER BY a.application_id
LIMIT 5;


