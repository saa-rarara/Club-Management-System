INSERT INTO Club_President
(student_id, club_id, start_date, end_date, assignment_status)
SELECT student_id, club_id, CURDATE(), NULL, 'Active'
FROM (
    SELECT
        student_id,
        club_id,
        ROW_NUMBER() OVER (
            PARTITION BY club_id
            ORDER BY RAND()
        ) AS rn
    FROM Memberships
) AS random_members
WHERE rn = 1;

