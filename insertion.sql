-- 9. APPLICATIONS
CREATE TABLE Applications (
    application_id INT AUTO_INCREMENT PRIMARY KEY,
    club_id INT NOT NULL,
    student_id INT NOT NULL,
    title VARCHAR(150) NOT NULL,
    description TEXT,
    submission_date DATETIME NOT NULL,
    application_status VARCHAR(30) NOT NULL,

    proposed_start DATETIME NOT NULL,
    proposed_end DATETIME NOT NULL,
    requested_venue VARCHAR(150) NOT NULL,
    event_purpose TEXT,

    funding_required BOOLEAN NOT NULL DEFAULT FALSE,
    requested_amount DECIMAL(12,2) NULL,
    funding_purpose TEXT NULL,

    FOREIGN KEY (club_id)
        REFERENCES Clubs(club_id),

    FOREIGN KEY (student_id)
        REFERENCES Students(student_id),

    CHECK (proposed_end > proposed_start),

    CHECK (
        (funding_required = FALSE
         AND requested_amount IS NULL
         AND funding_purpose IS NULL)
        OR
        (funding_required = TRUE
         AND requested_amount > 0
         AND funding_purpose IS NOT NULL)
    )
);

-- 10. APPROVAL DECISIONS
CREATE TABLE Approval_Decisions (
    decision_id INT AUTO_INCREMENT PRIMARY KEY,
    application_id INT NOT NULL,
    faculty_id INT NULL,
    admin_id INT NULL,
    decision VARCHAR(20) NOT NULL,
    comments TEXT,
    decision_date DATETIME NOT NULL,

    FOREIGN KEY (application_id)
        REFERENCES Applications(application_id),

    FOREIGN KEY (faculty_id)
        REFERENCES Faculty_Advisors(faculty_id),

    FOREIGN KEY (admin_id)
        REFERENCES Admin_Representatives(admin_id),

    CHECK (
        (faculty_id IS NOT NULL AND admin_id IS NULL)
        OR
        (faculty_id IS NULL AND admin_id IS NOT NULL)
    ),

    CHECK (
        decision IN ('Approved', 'Rejected', 'Pending')
    ),

    UNIQUE (application_id, faculty_id),
    UNIQUE (application_id, admin_id)
);






